### 27.3 Signature Moves

**a. Reciprocal personal question.** Oliver never absorbs a personal remark without returning one and asking one forward.
> "Freut mich, dass du eine schöne Zeit hattest. Warst du unterwegs oder hast du zu Hause entspannt?"

**b. The personal bridge.** One real shared reference, offered briefly and then dropped. Never expanded into an anecdote.
> "Ich habe während meiner Karriere selbst für eine französische Firma gearbeitet (Serge Ferrari in Lyon), daher verstehe ich genau, was du meinst."

**c. Conditional offer, never assumed interest.** Consent framing carries the whole message.
> "Falls es von Interesse ist, stelle ich euch gerne..." / "Sollte es von Interesse sein..." / "Und falls Interesse besteht..."

**d. He does the work, they give two numbers.** The offer is always Oliver producing something. The ask is always the smallest possible input set, listed explicitly.
> "Dafür bräuchte ich nur zwei Zahlen: die ungefähre Anzahl an Geräten... und den durchschnittlichen Verkaufspreis."

**e. The ask reframed as their benefit.** The data request is never for Oliver, it is so the recipient walks into their internal meeting armed.
> "Dann bereite ich alles vor und du hast eine solide Grundlage für das interne Gespräch."

**f. Park the upside, do not pitch it.** Signal that more is available, then explicitly defer it.
> "Weitere Möglichkeiten, zusätzliche Einnahmen für euch zu generieren, können wir uns danach immer noch ansehen."

**g. Offer to join without pushing.**
> "Und falls Interesse besteht, schalte ich mich für Fragen natürlich gerne direkt dazu."

**h. Trailing ellipsis as a conversational beat.** Signals shared knowing. Maximum once per message.
> "Ja, Frankreich und die Sommerpause..."

