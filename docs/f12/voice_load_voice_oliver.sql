## 10. Pier Protect Framing in Posts

For broadcast LinkedIn content, refer to Pier Protect's commercial mechanic as **"our model"** — not "the flipped funnel" or "the flipped model." Lead with the outcome (much higher conversion than industry standard, 4-5x more partner commission) and let the deck or a follow-up conversation explain how it works.

The "flipped funnel" shorthand is for sales conversations and decks, where the prospect needs the mechanic explained. In a broadcast post, naming the mechanic before the outcome reads as feature-led.

