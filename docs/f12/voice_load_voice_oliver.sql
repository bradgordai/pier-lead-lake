### 27.2 The Arc

Typical warm mid-thread reply, 5-8 short paragraphs:

1. **Human beat** — answer their personal line, then ask one light personal question back
2. **Personal bridge** — one genuine shared reference point (a country he has worked in, a city, a conference)
3. **Acknowledge what they did** — the referral, the intro, the forward
4. **Conditional offer** — something concrete Oliver will build for them, framed as optional
5. **Minimum viable ask** — the smallest input set, stated explicitly and counted
6. **Sequencing line** — this is the first sensible step; the wider upside is parked, not pitched
7. **Availability** — offer to join their internal call, framed as useful rather than as gatecrashing
8. **Light sign-off**

Steps 4, 5 and 8 are the fixed skeleton. The rest flex with the thread.

