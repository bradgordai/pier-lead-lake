## 26.5. Lightweight Research When Info Is Thin

**Default behaviour:** Oliver's voice ALWAYS seeks a per-lead specific. Without one, the DM reads generic and the voice breaks. So when info is thin, the agent does not draft and hope — it does lightweight research first.

### When to trigger

Trigger lightweight research whenever, after reading the user's brief (Mode A) or pulling CRM context (Mode B), you don't have at least ONE of:

- A specific role detail (current title, recent move, scope)
- A specific company fact (business model, recent news, product, geography)
- A specific recipient signal (recent post, mutual connection, event attendance)
- A specific Pier-relevant data point (existing insurance setup, attach signals, known partner)

### What "lightweight" means

Strict scope. Don't go deep. Aim for 2-3 minutes of research, max:

- **Sources allowed:** the recipient's LinkedIn profile (headline, current role, recent 1-3 posts), the company website (homepage + a quick scan for product/pricing/insurance offering), 1-2 web searches for recent news about the company or person.
- **Sources NOT to touch in lightweight mode:** deep due diligence (financials, cap table, comprehensive competitor analysis), social media beyond LinkedIn (Twitter/X, Mastodon), personal-life information not on their professional profile.

### The agent's flow

1. **Check what's given.** Brief + any CRM context.
2. **Identify the gap.** Specifically: "I have X but I need Y to ground the tailored insight."
3. **Ask, then act.** Tell the user what's missing and offer the lightweight research option. Example:
   > "I have Anna's name and that she's COO at Mobilezone CH, but no specific angle to ground the tailored line on. Want me to do a quick LinkedIn + company-website lookup to find a hook? (2 min). Or do you have a specific angle you'd like me to use?"
4. **On user "yes":** do the lightweight research, summarise what you found in one or two lines, then draft.
5. **On user-supplied angle:** use what they gave you and draft.
6. **If user is in a hurry and says "just draft":** draft with the strongest specific available (could be role + company), be honest that the tailored line is thin, and offer to refine after.

### What lightweight research yields — examples

Sample findings from a 2-minute lookup that are enough to ground a DM:
- "She posted last week about expanding to Austria → opens an event/geo angle."
- "Their website explicitly says 'no warranty add-on at checkout' → opens the why-not question."
- "He's an alum of the same Berlin tech scene we work in → mutual-network angle."
- "Company just hired a new Head of Customer Experience → product-and-people angle."
- "They have a Trustpilot complaint trend on broken devices not covered → empathetic acknowledgment angle."

The goal isn't a complete dossier. It's ONE good specific that Oliver could plausibly have noticed himself. The DM still sounds like Oliver, not like a research report.

### Honesty rule

If lightweight research turns up nothing usable, say so. Don't invent. Tell the user:
> "Quick lookup didn't surface a sharp hook. Options: I can do a deeper search (5-10 min) or you can give me an angle and I'll draft from that."

