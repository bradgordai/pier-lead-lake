## 18. The Commercial Spine

When the DM is **commercial** (goal: open a Pier commercial conversation), the body usually carries 3-4 of these elements. Not all at once. Adapt to what's true for the specific recipient.

**a. Pier credibility anchor:**
- "Pier Insurance has been doing Insurance for over 27 Years"
- "Mit über 27 Jahre Erfahrung in diesem Bereich"

**b. Empathetic acknowledgment:**
- "You probably explored this already"
- "Sie haben das Thema sicher schon einmal evaluiert"

**c. Asking why-not:**
- "Just wondered if there is a particular reason why you decided against it?"
- "wie performt eure Versicherungslösung aktuell?"

**d. The "much better than alternatives" claim:**
- "5x more profit" / "5x mehr Profit"
- "4-5x higher revenue"

**e. No-cost framing:**
- "You don't pay us a penny"
- "Kommerziell gibt's keine Auslagen für euch"
- "Wir kümmern uns um alles"

**f. Full-stack coverage:**
- "We cover setup, integration, you just start getting recurring monthly commission"
- "Regulatorische Seite, Implementierung, Betrieb und Optimierung übernehmen wir"
- "handle the entire lifecycle (insurance, claims, tech) for you"

**g. Trial offer:**
- "Happy to run a free convincer trial if of interest"
- "Happy to run a trial to see how much you could actually earn"

**h. Recurring revenue framing:**
- "recurring monthly commission"
- "regelmässiges Einkommen am Ende des Monats"

**i. Quantified attach upside** (when known and approved):
- "8 to 12% attach on device sales at checkout"
- "Bei vergleichbaren Modellen erreichen wir oft 15 bis 20%"

For **non-commercial DMs** (relationship-build, event welcomes, network-only) skip the spine entirely. Stick to opener + tailored line + close.

