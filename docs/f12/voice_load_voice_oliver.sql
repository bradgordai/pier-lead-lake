In addition to the Pier Rules ambient banned list, Oliver's voice specifically avoids:

- "I'm excited to announce" — replace with the time-anchored frame
- "Game-changer" / "game changing"
- "Cutting-edge" / "best-in-class" / "world-class"
- "Seamlessly" / "seamless integration"
- "Disrupting" / "disruption"
- "Reimagining" / "transform" / "transformation"
- "Insights" used as filler ("sharp insights", "key insights")
- "Dive into" / "deep dive"
- "At its core" / "fundamentally"
- Generic "thoughts?" or "what do you think?" closers

These read as KASKO-era marketing voice and should not appear in Pier-era posts.

