## 26. Context Modes — Standalone vs CRM-Integrated

This skill works in two modes. The voice (sections 16-25) is identical across both. **Both modes require at least one tailored specific** (section 19). What changes is the **source** of that specific.

### Mode A — Standalone

The user provides recipient name + a brief. No structured CRM data behind the request.

**Example user prompt:** "Draft a LinkedIn DM in Oliver's voice for Anna Petrova, COO at Mobilezone Switzerland."

**Agent behaviour:**
1. Extract any specifics the user has provided in the brief.
2. If the user has shared enough to ground the tailored insight (section 19) — draft.
3. If the brief is thin (just a name, or just name + company), trigger lightweight research per section 26.5 before drafting. Don't draft a generic message and don't fabricate.
4. Apply voice patterns (sections 16-25) directly.
5. Skip PS unless something specific is worth dropping in.
6. Don't reference Pier-process-specific things (Lead Lake, Companies tab, sn_list_logic.yml) — those don't exist in this context.

### Mode B — CRM-Integrated (Pier Lead Lake workflow)

The user is operating inside the Pier outreach system. The recipient has a PID in the Lead Lake, a Companies tab entry, an SN list bucket, and possibly an SN account note.

**Example user prompt:** "Draft the welcome for P304 Benjamin Lode."

**Agent behaviour:**
1. Apply the same voice patterns (sections 16-25).
2. ADDITIONALLY consult these CRM inputs before drafting:
   - Contacts tab (col B for Co-ID, X for background notes, AE for SN List)
   - Companies tab (S/T/U/V/Y/Z for insurance status, AD for USP/Notes — Pier's authoritative view of the company)
   - `sn_list_logic.yml` (bucket assignment — event_meeting vs pier_target vs relationship vs exclusion)
   - SN account note (verbatim text, expanded if truncated per `rules.yml::sn_note_must_expand_truncated_before_use`)
   - Prior thread check (per `rules.yml::check_existing_message_thread_before_drafting` — halt if a thread already exists)
3. The bucket determines tone:
   - **event_meeting** → tailored insight is about the event + recipient context
   - **pier_target** → commercial spine (section 18) applies fully
   - **relationship / exclusion** → no commercial spine, relationship-only tone
4. Cross-channel variation: check existing T-rows for the contact, don't repeat verbatim phrasing.
5. If CRM data is incomplete (e.g., Co-row missing, no SN note, lead-lake row stale), Mode A's lightweight research (section 26.5) can supplement.

### How to tell which mode you're in

- Mode A signals: user provides facts in the prompt itself, no PID, no reference to Lead Lake / Companies tab / SN list
- Mode B signals: user references a PID (P###), mentions Lead Lake / Companies tab / sn_list_logic.yml / sweep_state.yml / inter_agent_handover.md, or the request implies a structured workflow

When in doubt, ask the user which mode applies.

