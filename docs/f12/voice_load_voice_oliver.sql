# Oliver's Voice — LinkedIn Posts AND DMs

Oliver Mueller is Senior Business Development Manager at Pier Insurance, leading partner acquisition for Pier Protect and supporting Ticketplan, with DACH as his territory. This skill captures how Oliver writes LinkedIn POSTS and 1st-degree DMs / Soft-Welcomes under his own name. It does not replace Pier Rules or Pier Terminology — those apply ambient. This skill is the layer on top.

**Sections 1-15 cover POSTS. Sections 16-25 cover DMs. Section 26 explains context modes (standalone vs CRM-integrated). Section 26.5 covers lightweight research when info is thin. Section 27 covers warm mid-thread EMAIL REPLIES, including the light-touch rule for editing Oliver's own drafts (27.6).**

Routing out of this skill:
- Mid-thread LinkedIn reply-replies and CR notes (connection request notes) go to the **LinkedIn Message Architect**.
- Cold email, first-touch follow-up and event messaging go to the **Email Architect**.
- Anything written under another Pier person's name uses the Pier Rules ambient voice, not this skill.

