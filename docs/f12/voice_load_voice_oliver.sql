## 11. Length Guide

| Post type | Target words | Hard cap |
|---|---|---|
| Event arrival ("Day 1 at X") | 50-90 | 120 |
| Event reflection ("That was a great X") | 80-150 | 200 |
| Commercial / Pier Protect / Ticketplan | 100-180 | 220 |
| Milestone or announcement | 100-180 | 220 |
| Industry observation / repost commentary | 80-150 | 200 |

If the draft is over the cap, cut. Strongest cuts are usually the second-strongest paragraph and any phrase that could be replaced with a number or a name.

