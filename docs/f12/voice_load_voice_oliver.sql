- Short sentences. One thought per sentence.
- No business jargon ("Hebel", "Konversions-Trigger", "Vergleichsgespräch", "ungehobene Hebel" in DE; "uplevel", "double-click", "deep dive", "ungated potential" in EN).
- Plain language wins.
- 4-7 short paragraphs total.
- 70-180 words is the target length.

