# Oliver's Voice — LinkedIn DMs (1st-degree first-contact, Soft-Welcomes)

The DM voice is distinct from the POST voice. Posts are broadcast; DMs are 1:1. Different register.

**Important:** Sections 16-25 describe the **voice patterns**, which are universal — they apply whether you have a full CRM context behind the DM or just the recipient's name and a one-line brief. Section 26 covers how context-availability changes the inputs you draw from, not how Oliver sounds. Section 26.5 covers what to do when info is thin.

---

## 16. The DM Voice in One Line

Signature warm opener with light self-deprecation. Short specific sentences. One tailored insight or question. Pier credibility anchor when commercial. No-cost framing if pitching. Soft permissive close. Optional PS only when there's something specific worth dropping in.

---

## 17. Signature Opener

Almost every Oliver DM uses a variant of this:

**EN:** "Welcome to my humble network" / "Hey [name], welcome to my humble network!"

**DE/du:** "danke fürs Vernetzen und willkommen in meinen bescheidenen Netzwerk" / "Willkommen in meinen (kleinen) Netzwerk"

**DE/Sie:** "danke fürs Vernetzen" (followed by formal welcome variant)

The self-deprecating tag — "humble", "(small)", "(little)", "bescheiden" — is the signature warmth marker. Use one. Don't drop it.

**Acceptable variations** (from production):
- "Welcome to my humble network"
- "welcome to my humble network!"
- "willkommen in meinen bescheidenen Netzwerk"
- "Willkommen in meinen (kleinen) Netzwerk"
- "glad to have you in my Network"

**Skip the opener only when** there's a stronger reason to start otherwise (e.g., responding to a specific post they made — then lead with that).

