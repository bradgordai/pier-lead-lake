## 1. The Voice in One Line

First-person. Time- or scene-anchored opening. Short paragraphs. One sharp contrast or stat. Named specifics. Soft commercial close. Sparse emoji.

That's the spine. The rest of this file is the detail.

---

## 2. Opening Hooks — Pick One

Oliver's posts almost always open with one of these moves. Avoid generic openings ("In today's fast-paced world", "I'm excited to share", "Have you ever wondered").

**a. Time-anchored personal hook.** Best for announcements, reflections, milestones.
- "A week in at Pier Insurance, and it feels right to make it official."
- "Two weeks in at Pier, and one stat keeps coming up in my conversations."
- "Today was my last day at KASKO."

**b. Scene or setting with one emoji.** Best for event posts, travel posts, "here I am" moments.
- "🚇 Tube was surprisingly spacious this morning, the calm before the buzzing atmosphere of Day 2."
- "☀️ Day 1 at Insurtech Insights Europe and the sun is actually showing up in London."

**c. Stat or observation as the lead.** Best for commercial posts where the punch is the point.
- "Industry-standard gadget insurance attach is 1-2%."
- "One topic kept coming up at the Global InsurTech Summit today: the EU AI Act."

**d. Direct first-person reaction.** Best for reposts and industry commentary.
- "Really excited to be at the Global Insurtech Summit today."
- "Looking forward to learning more in this session."

Don't open with a question. Don't open with a buzzword. Don't open with "I'm excited to announce" — Oliver sometimes uses a softer "delighted to share" register, but the time-anchored personal frame is stronger and should be preferred.

---

## 3. Structure

Short paragraphs. Most lines are one or two sentences. Use line breaks aggressively — LinkedIn rewards white space.

Typical post arc (5-9 paragraphs):

1. **Hook** — one of the four openings above
2. **Context** — what this is about, in one or two lines
3. **Substance** — the meat: a stat, a contrast, a named partner, a specific observation. The strongest single line in the post is usually here.
4. **Proof or texture** — partners, people, events. Specifics that show this isn't theory.
5. **Soft commercial close** — invites a conversation, never demands one
6. **Hashtags** — 2-4 specific ones on their own line below the body

Don't write a wall of text. Don't write a ten-paragraph think-piece. If the post is over ~220 words, cut.

---

## 4. The Sharp Line

Most of Oliver's strongest posts have one line that crystallises the point. Usually a contrast or a specific number. Example shapes:

- "Most insurance operations stitch vendors together. Pier runs the whole thing in-house."
- "Industry-standard attach is 1-2%. Our model runs at 8-12%."
- "One team, one phone number, one accountable partner."

When drafting, find the sharp line first, then build the post around it.

---

## 5. Specifics, Not Abstractions

Oliver names things. Real partners. Real people. Real events. Real numbers (within Pier's approved facts list).

- Use Phones Direct, Reboxed, Big Phone Store when externally cleared (per Capability Reference).
- Tag people genuinely thanked or genuinely relevant. Not for reach-bait.
- Name the conference, the venue, the speaker.
- Name the number when it's approved.

Avoid: "leading retailers", "innovative partners", "industry players". Filler.

---

## 6. Emoji — Sparse and Earned

The recent Pier-era posts use emoji sparingly. The KASKO-era posts often overdid it. Calibrate to the recent voice.

**Acceptable:**
- One emoji at the start of a scene-setting opener (🚇 ☀️ 🎉 🚀)
- One emoji at the end of a milestone announcement ("On to the next chapter. 🚀")
- 🇬🇧 🇪🇺 🇩🇪 when geography is being directly referenced
- ☕ 🤝 in genuinely casual event posts

**Avoid in this voice:**
- ✅ ✔️ 🔹 👉 as bullet markers — these read as KASKO-era. Use line breaks and prose instead.
- 💡 🚀 💪 ✨ sprinkled mid-post for emphasis — don't use as visual punctuation.
- More than 3 emoji in a single commercial post; aim for 0-1.

If a post is about a serious commercial point (attach rates, regulatory matters, partner economics), aim for zero or one emoji. Save the warmth for human moments.

---

## 7. Hashtags

2-4 specific hashtags on their own line at the end. Pier-relevant ones first.

Common Oliver hashtag sets:
- Pier Protect: #PierInsurance #EmbeddedInsurance #GadgetInsurance
- Ticketplan: #Ticketplan #TicketRefundProtection #LiveEvents
- Events: the specific event hashtag, then one or two industry tags
- DACH-relevant: #DACH or country flags, used sparingly

Avoid hashtag stuffing. 6+ reads as reach-grabbing.

---

## 8. The Commercial Close

Oliver's posts are commercially honest but never pitchy. The close invites a conversation, doesn't demand one.

**Use shapes like:**
- "If your attach numbers look like the industry average, happy to chat."
- "If you're exploring how embedded gadget insurance might fit your business, drop me a message."
- "Always happy to compare notes."
- "If you're [specific situation], the deck below is worth a scroll."

**Don't use:**
- "Book a meeting"
- "Schedule a call"
- "DM me to learn more"
- Any hard CTA that puts pressure on the reader
- Generic "what do you think?" engagement-bait

