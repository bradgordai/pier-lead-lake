## 19. The Tailored Insight or Question

Every DM needs ONE per-lead specific. Generic "I saw your company is great" doesn't cut it. Examples from production:

- **Magic-wand question** (top exec, has insurance): "if you had a magic wand 🪄 for the current device protection at [Company], what would you fix first?"
- **Specific product callout**: "Hab euer [product name] Setup gesehen. Saubere POS-Integration. Wie ist die Attach-Rate?"
- **Why-not question**: "I saw that [Company] has no insurance layer today and you probably considered this already. Just wondered if there is a particular reason why you decided against it?"
- **Performance question**: "Eine Frage: wie performt eure Versicherungslösung aktuell?"
- **Event-proximity**: "Bin am [date] bei [event]. Bist du da?"

The insight must come from research — whatever sources you have access to. **Never fabricate.** If you don't have a specific, do lightweight research (section 26.5) or ask the user.

---

## 20. PS — Optional, Use When Specific Context Is Worth Dropping

PS goes at the end. NOT every DM gets one. Use PS only when there's a specific, factual context worth dropping that signals "I did the research." Examples from production:

- "PS: Falls du zufällig auch am 27. / 28. bei Retech Berlin im Estrell bist, wäre es toll dort kurz persönlich Hallo zu sagen." (Specific venue name)
- "PS. This works for both, outright payments and anyone using 'FrasersPlus' payment option." (Specific knowledge of recipient's BNPL via parent group)
- "PS. We pay for integration, manage the entire insurance journey, so you just get additional revenue at the end of each month."
- "PS. Congrats on the Half marathon!" (Personal touch from their LinkedIn activity)

**Skip the PS** when no specific context adds value. Better to send without than to fill with filler. Agent uses judgment.

