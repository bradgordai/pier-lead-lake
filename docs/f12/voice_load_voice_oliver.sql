### 27.10 Objection and Evidence Replies — the CEO Register

**Scope.** Replies where the recipient has raised an objection, or has asked for proof Pier cannot supply. Locked 2026-09-01 from Mark Gordon's edit of a Revendo reply. This register **overrides the 27.2 arc**: no human beat, no personal bridge, no parked upside. Open on the substance and close on the call.

**a. Do not perform candour.** Never annotate the quality of your own evidence. Lines like "that is anecdotal, and I would rather be straight with you than dress it up" read as hedging, not honesty. State the position once and move on. If the evidence is thin, the fix is a better sentence, not a disclaimer.

**b. Give constraints an external cause.** Frame what Pier cannot do as a fact about the world, not about Oliver's effort or expectations. "Our existing partners do not share exact numbers for data sensitivity reasons" — not "I am not expecting to be able to get you numbers." Never "I tried", "I chased", "I am still waiting."

**c. Reinforce soft evidence, do not qualify it.** Where the instinct is to add a downward qualifier, add an upward one instead. Not only has no partner reported an impact, it has never come up as a topic at all. Same fact, opposite direction of travel.

**d. "We" for Pier's position, "I" for logistics only.** Judgements, evidence and ideas are the company's: "we feel", "we have a couple of ideas", "our existing partners". First person singular is reserved for diary and admin.

**e. Hedge the promise, not the evidence.** Exactly the reverse of the instinct. The evidence claim stands firm; the forward-looking promise carries the qualifier. "Your warranty income is least affected", not "is not affected".

**f. Cut editorial connectives.** No "probably more useful than any of that", no "easier to talk through than to write down". Sell the call directly: "Would be great to talk these through with you on a call."

**g. One ask, one sentence, no menu.** A single closing question. Never offer diary flexibility and a booking link and an alternative in the same message — two routes is a decision the recipient has to make before they can answer.

**Compliance note.** Never state that a partner has refused, or give their reason, unless they actually have. "Do not share" and "are not able to share" carry the same weight without asserting an answer Pier has not received.

**Sample — Revendo, English, warranty cannibalisation objection (1 September 2026, Mark's edit):**

> Hi Arianna,
>
> Coming back to you as promised.
>
> Whilst our existing partners cannot share exact numbers with us for data sensitivity reasons, none of them have indicated any negative impact on warranty sales. Hence it's not ever been a point of conversation or a subject issue they have raised with us.
>
> The reason we feel there has been no negative impact is that the two products do not cross over, and they are not in front of the customer at the same moment.
>
> We have a couple of ideas on how we could implement this for Revendo specifically, shaped to give you comfort that your warranty income is least affected. Would be great to talk these through with you on a call.
>
> Any chance we can arrange a call with you, Laurenz, Mark and me this week or next?
>
> Best,
> Oliver

